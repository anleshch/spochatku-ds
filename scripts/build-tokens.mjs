// Turns tokens/figma-variables.json (exported from Figma) into src/tokens/tokens.css.
//
// Figma modes map to CSS like this:
//   Semantic   pink-bg (default) | beige-bg      → [data-theme="beige-bg"]
//   Components default | inverse | outlined      → [data-mode="inverse"], [data-mode="outlined"]
// Aliases stay aliases (var(--…)), so the component → semantic → primitive chain is kept in CSS.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(resolve(root, 'tokens/figma-variables.json'), 'utf8'));
const outFile = resolve(root, 'src/tokens/tokens.css');

const FONT_WEIGHTS = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700, ExtraBold: 800, Black: 900 };
const FONT_FALLBACKS = { Oi: 'serif', 'Golos Text': 'system-ui, sans-serif' };
const PX_CATEGORIES = ['space/', 'radius/', 'border-width/', 'blur/', 'size/', 'typography/size/', 'typography/line-height/'];

const cssName = (name) => `--${name.replaceAll('/', '-')}`;
const ref = (name) => `var(${cssName(name.replace(/^\{|\}$/g, ''))})`;

function primitiveValue(name, value) {
  if (name.startsWith('typography/weight/')) return FONT_WEIGHTS[value];
  if (name.startsWith('typography/family/')) return `'${value}', ${FONT_FALLBACKS[value] ?? 'sans-serif'}`;
  if (typeof value === 'number' && PX_CATEGORIES.some((p) => name.startsWith(p))) return `${value}px`;
  return value;
}

const decl = (entries) => entries.map(([name, value]) => `  ${cssName(name)}: ${value};`).join('\n');
const block = (selector, entries) => `${selector} {\n${decl(entries)}\n}`;

// Primitives — one mode
const primitives = Object.entries(src.Primitives).map(([n, v]) => [n, primitiveValue(n, v)]);

// Semantic — modes pink-bg / beige-bg
const semantic = (mode) => Object.entries(src.Semantic).map(([n, v]) => [n, ref(v[mode])]);

// Components — value is either one alias (same in all modes) or [default, inverse, outlined]
const [DEFAULT, INVERSE, OUTLINED] = [0, 1, 2];
const components = (i) =>
  Object.entries(src.Components).map(([n, v]) => [n, ref(Array.isArray(v) ? v[i] : v)]);
const onlyDiffering = (i) =>
  Object.entries(src.Components)
    .filter(([, v]) => Array.isArray(v) && v[i] !== v[DEFAULT])
    .map(([n, v]) => [n, ref(v[i])]);

// Text styles → utility classes, bound to typography primitives
const textClasses = Object.entries(src.textStyles).map(([name, s]) => {
  const cls = `.text-${name.replaceAll('/', '-')}`;
  return `${cls} {
  font-family: ${ref(s.fontFamily)};
  font-weight: ${ref(s.fontStyle)};
  font-size: ${ref(s.fontSize)};
  line-height: ${ref(s.lineHeight)};
}`;
});

// Component tokens are re-declared on every theme/mode scope: a CSS var that references
// another var resolves where it is declared, so a nested [data-theme] must recompute them.
const css = `/* Generated by scripts/build-tokens.mjs from tokens/figma-variables.json — do not edit. */

/* Primitives */
${block(':root', primitives)}

/* Semantic — pink-bg (default) */
${block(':root, [data-theme="pink-bg"]', semantic('pink-bg'))}

/* Semantic — beige-bg */
${block('[data-theme="beige-bg"]', semantic('beige-bg'))}

/* Components — default */
${block(':root, [data-theme], [data-mode="default"]', components(DEFAULT))}

/* Components — inverse */
${block('[data-mode="inverse"]', onlyDiffering(INVERSE))}

/* Components — outlined */
${block('[data-mode="outlined"]', onlyDiffering(OUTLINED))}

/* Text styles */
${textClasses.join('\n\n')}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, css);
console.log(
  `tokens.css: ${primitives.length} primitives, ${Object.keys(src.Semantic).length} semantic, ` +
    `${Object.keys(src.Components).length} component tokens, ${textClasses.length} text styles`,
);
